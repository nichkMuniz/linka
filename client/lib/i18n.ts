export type TranslationKey = keyof typeof pt;

// Preenchido por `loadLanguage("en")`.
let enTranslations: Record<TranslationKey, string> | null = null;

const STORAGE_KEY = "ritmofit-language";

/**
 * Idioma do app: a escolha salva e, sem ela, o do aparelho (qualquer variante
 * de português → `pt`; o resto → `en`). Fonte ÚNICA — o `language-context`, o
 * `tUi`, o `getUiLanguage` do ritmofit-db e o `formatTimeAgo` leem daqui. Antes
 * só o contexto olhava o aparelho: num iPhone em inglês sem escolha salva, a
 * tela saía em inglês e o que é traduzido fora do React (notificação, Face ID,
 * card de treino, nome dos exercícios do catálogo) saía em português.
 */
export function resolveLanguage(): Language {
  try {
    const stored = localStorage.getItem(STORAGE_KEY);
    if (stored === "en" || stored === "pt") return stored;
  } catch {
    /* storage indisponível — cai no aparelho */
  }
  try {
    const tags = [
      ...(Array.isArray(navigator.languages) ? navigator.languages : []),
      navigator.language,
    ].filter(Boolean);
    return (tags[0]?.toLowerCase() ?? "").startsWith("pt") ? "pt" : "en";
  } catch {
    return "pt";
  }
}

/** Grava a escolha do usuário (a partir daí ela vence o idioma do aparelho). */
export function persistLanguage(lang: Language) {
  try {
    localStorage.setItem(STORAGE_KEY, lang);
  } catch {
    /* best-effort */
  }
}

export function isLanguageLoaded(lang: Language): boolean {
  return lang === "pt" || enTranslations !== null;
}

let enLoading: Promise<void> | null = null;

/** Garante o dicionário do idioma na memória. Português já está; inglês é baixado uma vez. */
export function loadLanguage(lang: Language): Promise<void> {
  if (isLanguageLoaded(lang)) return Promise.resolve();
  enLoading ??= import("./i18n-en")
    .then((m) => {
      enTranslations = m.en;
    })
    .catch(() => {
      // Falhou (raríssimo: o arquivo é local no app) — segue em português e
      // permite tentar de novo depois.
      enLoading = null;
    });
  return enLoading;
}

export function t(lang: Language, key: TranslationKey): string {
  if (lang === "en" && enTranslations) return enTranslations[key] ?? pt[key] ?? key;
  return pt[key] ?? key;
}

/**
 * Tradução para código FORA do React (notificação local, prompt do Face ID,
 * card em canvas, erros do ritmofit-db). Usa o mesmo idioma da tela.
 */
export function tUi(key: TranslationKey): string {
  return t(resolveLanguage(), key);
}
